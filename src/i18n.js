class SimpleI18n {
  constructor(translations) {
    this.translations = translations;
    this.locale = "ru";
    this.defaultLocale = "ru";
  }

  t(key) {
    const currentDict = this.translations[this.locale] || this.translations[this.defaultLocale];
    if (currentDict && currentDict[key]) return currentDict[key];
    const defaultDict = this.translations[this.defaultLocale];
    if (defaultDict && defaultDict[key]) return defaultDict[key];
    return key;
  }
}

